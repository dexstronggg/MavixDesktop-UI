def stats_log_path() -> str:
    return str(settings.log_path.parent / 'stats_ГГГГ-ММ-ДД.jsonl')


def as_html() -> str:
    def rows(items: tuple[tuple[str, ...], ...]) -> str:
        out = []
        for item in items:
            unit = (
                f'<span style="color:#8893A4">, {item[1]}</span>'
                if len(item) == 3
                else ''
            )
            out.append(
                f'<tr>'
                f'<td style="padding:3px 16px 3px 0; color:#22d3ee">{item[0]}{unit}</td>'
                f'<td style="padding:3px 0">{item[-1]}</td>'
                f'</tr>'
            )
        return '<table cellspacing="0">' + ''.join(out) + '</table>'

    return (
        '<div style="font-size:14px">'
        '<h3 style="color:#E8EEF5; margin:0 0 6px 0">Горячие клавиши</h3>'
        f'{rows(HOTKEYS)}'
        '<p style="color:#8893A4; margin:6px 0 16px 0">'
        'Буквенные клавиши работают в любой раскладке — и в английской, и в русской.</p>'
        '<h3 style="color:#E8EEF5; margin:0 0 6px 0">Индикатор связи внизу слева</h3>'
        f'{rows(INDICATORS)}'
        '<h3 style="color:#E8EEF5; margin:16px 0 6px 0">Показатели (клавиша S или Ы)</h3>'
        f'{rows(METRICS)}'
        '<h3 style="color:#E8EEF5; margin:16px 0 6px 0">Рекомендация режима камеры</h3>'
        f'{rows(ADVICE)}'
        '<p style="color:#8893A4; margin:6px 0 0 0">'
        'Появляется под таблицей показателей не раньше чем через 10 секунд после '
        'подключения. Это только подсказка — переключение режима камеры программа '
        'не делает сама, решение всегда за вами (панель настроек камеры, кнопка '
        '«Сохранить»).</p>'
        '<h3 style="color:#E8EEF5; margin:16px 0 6px 0">Запись в файл</h3>'
        '<p style="margin:0">Пока открыт экран дрона, все показатели записываются '
        'раз в секунду в файл:</p>'
        f'<p style="margin:6px 0; color:#22d3ee; font-family:monospace">{html.escape(stats_log_path())}</p>'
        '<p style="margin:0">Одна строка — одна секунда, примерно мегабайт за час полёта. '
        'Разобрать записанное после посадки:</p>'
        '<p style="margin:6px 0; color:#22d3ee; font-family:monospace">'
        './scripts/stats_report.py &lt;файл&gt;</p>'
        '</div>'
    )
